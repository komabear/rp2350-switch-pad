/* device descriptor (mirrors real pad: bcdUSB 2.00, per-interface class) */
static const uint8_t powa_device_descriptor[18] = {
    0x12, 0x01,
    0x10, 0x01, /* bcdUSB 1.10 (matches real pad) */
    0x00, 0x00, 0x00,
    0x40,
    0xD6, 0x20, /* idVendor 0x20D6 (BDA/PowerA) */
    0x13, 0xA7, /* idProduct 0xA713 */
    0x00, 0x01, /* bcdDevice 1.00 */
    0x01, 0x02, 0x00,
    0x01,
};

