/*
 * powa_descriptors.h - PowerA "BDA NSW wired controller" (20D6:A713) identity.
 * Report descriptor dumped byte-for-byte from the user's real PowerA pad via
 * hidapi (102 bytes). Input report: 8 bytes.
 */
#pragma once
#include <stdint.h>

#define POWA_VID 0x20D6
#define POWA_PID 0xA713
#define POWA_REPORT_DESC_LEN 102
#define POWA_INPUT_REPORT_LEN 8

/* hat values: 0=N 1=NE 2=E 3=SE 4=S 5=SW 6=W 7=NW 0xF=center (!) */
#define POWA_HAT_CENTER 0x0F

/* button masks - byte 0 */
#define POWA_MASK_Y       (1U << 0)
#define POWA_MASK_B       (1U << 1)
#define POWA_MASK_A       (1U << 2)
#define POWA_MASK_X       (1U << 3)
#define POWA_MASK_L       (1U << 4)
#define POWA_MASK_R       (1U << 5)
#define POWA_MASK_ZL      (1U << 6)
#define POWA_MASK_ZR      (1U << 7)
/* button masks - byte 1 */
#define POWA_MASK_MINUS   (1U << 0)
#define POWA_MASK_PLUS    (1U << 1)
#define POWA_MASK_L3      (1U << 2)
#define POWA_MASK_R3      (1U << 3)
#define POWA_MASK_HOME    (1U << 4)
#define POWA_MASK_CAPTURE (1U << 5)

typedef struct __attribute__((packed)) {
    uint8_t buttons0; /* Y B A X L R ZL ZR */
    uint8_t buttons1; /* - + L3 R3 HOME CAPTURE, bits 6-7 pad */
    uint8_t hat_pad;  /* low nibble hat (F=center), high nibble 0 */
    uint8_t lx, ly, rx, ry; /* 0x80 center */
    uint8_t pad;
} powa_report_t; /* 8 bytes */

